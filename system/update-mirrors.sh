set -euo pipefail
if [[ $EUID -ne 0 ]]; then
   echo "This script must be run as root"
   exit 1
fi

echo "Updating mirrorlist with reflector..."

reflector --country 'United States' --latest 20 --age 12 --protocol https --sort rate --save /etc/pacman.d/mirrorlist

if [ $? -eq 0 ]; then
    echo "Mirrorlist updated successfully."
else
    echo "Reflector failed to update the mirrorlist."
fi
